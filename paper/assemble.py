"""Expand all local TeX inputs into the repository's standalone main.tex."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
pattern=re.compile(r'\\input\{([^}]+)\}')
def expand(text,stack=()):
 def include(m):
  rel=m.group(1);p=(ROOT/rel).resolve()
  if p.suffix!='.tex':p=p.with_suffix('.tex')
  assert p.is_relative_to(ROOT) and p not in stack,p
  return '\n% BEGIN '+str(p.relative_to(ROOT))+'\n'+expand(p.read_text(),stack+(p,))+'\n% END '+str(p.relative_to(ROOT))+'\n'
 return pattern.sub(include,text)
s=expand((ROOT/'paper/manuscript.tex.in').read_text())
assert not re.search(r'\\(?:input|include|includegraphics|bibliography)\s*[{[]',s)
# Schematic styles must remain local to those TikZ figures, not PGFPlots.
style=s[s.index('% BEGIN figures/schematics/style.tex'):s.index('% END figures/schematics/style.tex')]
style=re.sub(r'\\usepackage[^\n]*\n','',style)
# Keep colors/libraries global, apply node styles only within schematic groups.
a=style.index('\\tikzset');b=len(style)
node_style=style[a:b]
s=s.replace(node_style,'')
for name in ['01-intervention.tex','02-state-cell.tex']:
 marker='% BEGIN figures/schematics/'+name
 start=s.index(marker);end=s.index('% END figures/schematics/'+name,start)
 segment=s[start:end];s=s[:start]+'\\begingroup\n'+node_style+segment+'\\endgroup\n'+s[end:]
# Ordinary figure text uses the fonts selected in its source; the document body stays Latin Modern.
(ROOT/'main.tex').write_text('% Self-contained manuscript; generated by paper/assemble.py.\n'+s)
print('Wrote main.tex:',len(s.splitlines()),'lines, no external figure/table/bibliography inputs.')
